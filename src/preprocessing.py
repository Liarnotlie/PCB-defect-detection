    OUTPUT_DIR = "./pcb_dataset_cleaned"
    CLASSES = ['resistor', 'capacitor', 'connector', 'ic', 'led', 'diode', 'transistor', 'inductor', 'jumper', 'button']

    process_and_split_dataset(SOURCE_DIR, OUTPUT_DIR, CLASSES, split_ratio=(0.8, 0.1, 0.1))